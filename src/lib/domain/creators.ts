export const creatorById = (id: string) => CREATORS.find((c) => c.id === id);

export function statsFor(c: Creator, platform: Platform) {
  return c.platforms.find((p) => p.platform === platform);
}

export function primaryStats(c: Creator) {
  return [...c.platforms].sort((a, b) => b.medianViews - a.medianViews)[0];
}
