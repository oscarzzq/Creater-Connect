import type { Creator, NicheId, Platform, PlatformStats } from "./types";

/**
 * Platform stats from the last 20 organic videos. `spread` describes view
 * consistency: low spread = predictable creator, high spread = volatile.
 */
function ps(platform: Platform, followers: number, medianViews: number, spread = 0.4, engagementRate = 5): PlatformStats {
  return {
    platform,
    followers,
    medianViews,
    p25: Math.round(medianViews * (1 - spread * 0.9)),
    p75: Math.round(medianViews * (1 + spread * 1.6)),
    engagementRate,
  };
}
